package com.unitesk.requality.vscode.ui.swt.graphics;

/** {@code org.eclipse.swt.graphics.Rectangle}. */
public final class Rectangle {
  public int x;
  public int y;
  public int width;
  public int height;

  public Rectangle(int x, int y, int width, int height) {
    this.x = x;
    this.y = y;
    this.width = width;
    this.height = height;
  }
}
